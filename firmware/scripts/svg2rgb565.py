#!/usr/bin/env python3
"""Rasterise an axis-aligned SVG path to an RGB565 PROGMEM blob for the ST7735.

The mark's path uses only M/m H/h V/v L/l z, so every edge is horizontal or
vertical. A scanline even-odd fill reproduces it exactly; supersampling in y and
exact span-overlap in x give clean anti-aliasing without any imaging library.

    python3 svg2rgb565.py out.h                       # 112px LOGO, brand colour
    python3 svg2rgb565.py mascot.h --size 46 --name MASCOT
    python3 svg2rgb565.py m.h --path-file glyph.txt --size 64 --name GLYPH

Output is big-endian (MSB first) — the ST7735's native wire format — so each row
streams from flash straight to SPI with no per-pixel work.
"""
import argparse
import re
import sys

# Default: the Claude Code mark, 24x24 viewbox.
DEFAULT_PATH = (
    "M20.998 10.949H24v3.102h-3v3.028h-1.487V20H18v-2.921h-1.487V20H15v-2.921H9V20"
    "H7.488v-2.921H6V20H4.487v-2.921H3V14.05H0V10.95h3V5h17.998v5.949z"
    "M6 10.949h1.488V8.102H6v2.847z"
    "m10.51 0H18V8.102h-1.49v2.847z"
)


def parse(d):
    """-> list of subpaths, each a list of absolute (x, y) vertices."""
    toks = re.findall(r"([MmHhVvLlZz])|(-?\d*\.?\d+)", d)
    subs, cur, x, y, start = [], [], 0.0, 0.0, (0.0, 0.0)
    i = 0
    while i < len(toks):
        cmd = toks[i][0]
        if not cmd:
            raise ValueError("expected command")
        i += 1

        def num():
            nonlocal i
            v = float(toks[i][1])
            i += 1
            return v

        if cmd in "Mm":
            if cur:
                subs.append(cur)
            nx, ny = num(), num()
            x, y = (nx, ny) if cmd == "M" else (x + nx, y + ny)
            start = (x, y)
            cur = [(x, y)]
        elif cmd in "Zz":
            if cur:
                cur.append(start)
                subs.append(cur)
            cur = []
            x, y = start
        else:
            while i < len(toks) and not toks[i][0]:
                if cmd == "H":
                    x = num()
                elif cmd == "h":
                    x += num()
                elif cmd == "V":
                    y = num()
                elif cmd == "v":
                    y += num()
                elif cmd == "L":
                    x, y = num(), num()
                elif cmd == "l":
                    x, y = x + num(), y + num()
                cur.append((x, y))
    if cur:
        subs.append(cur)
    return subs


def rasterise(path, view, size, ss):
    subs = parse(path)
    edges = []  # vertical edges only; horizontals never cross a scanline
    for sp in subs:
        for (x0, y0), (x1, y1) in zip(sp, sp[1:]):
            if x0 == x1 and y0 != y1:
                edges.append((x0, min(y0, y1), max(y0, y1)))

    scale = size / view
    cov = [[0.0] * size for _ in range(size)]
    for row in range(size):
        acc = cov[row]
        for s in range(ss):
            ys = (row + (s + 0.5) / ss) / scale
            xs = sorted(x for (x, ylo, yhi) in edges if ylo <= ys < yhi)
            for a, b in zip(xs[0::2], xs[1::2]):
                xa, xb = a * scale, b * scale
                k0, k1 = int(xa), min(int(xb), size - 1)
                for k in range(k0, k1 + 1):
                    overlap = min(k + 1.0, xb) - max(float(k), xa)
                    if overlap > 0:
                        acc[k] += overlap / ss
    return cov


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("output", help="header file to write")
    ap.add_argument("--size", type=int, default=112, help="square output px")
    ap.add_argument("--view", type=float, default=24.0, help="SVG viewbox size")
    ap.add_argument("--name", default="LOGO", help="C symbol / macro base name")
    ap.add_argument("--ss", type=int, default=16, help="vertical supersamples")
    ap.add_argument("--fg", default="D97757", help="foreground hex RRGGBB")
    ap.add_argument("--path-file", help="read the SVG path 'd' from this file")
    args = ap.parse_args()

    path = open(args.path_file).read().strip() if args.path_file else DEFAULT_PATH
    fg = tuple(int(args.fg[i : i + 2], 16) for i in (0, 2, 4))

    cov = rasterise(path, args.view, args.size, args.ss)

    # ASCII preview so the shape can be eyeballed before it hits the panel.
    ramp = " .:-=+*#%@"
    step = max(1, args.size // 28)
    for row in range(0, args.size, step * 2):
        print(
            "".join(
                ramp[min(9, int(cov[row][c] * 9.99))]
                for c in range(0, args.size, step)
            ),
            file=sys.stderr,
        )

    with open(args.output, "w") as f:
        f.write(f"// Generated by svg2rgb565.py --name {args.name} --size {args.size}.\n")
        f.write("// RGB565, big-endian, pre-blended against black. Do not edit by hand.\n")
        f.write("#pragma once\n#include <Arduino.h>\n\n")
        f.write(f"#define {args.name}_W {args.size}\n")
        f.write(f"#define {args.name}_H {args.size}\n\n")
        f.write(f"const uint8_t {args.name}[{args.size * args.size * 2}] PROGMEM = {{\n")
        for row in range(args.size):
            line = []
            for col in range(args.size):
                a = min(1.0, max(0.0, cov[row][col]))
                r = round(fg[0] * a)
                g = round(fg[1] * a)
                b = round(fg[2] * a)
                w = ((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3)
                line += [(w >> 8) & 0xFF, w & 0xFF]
            for i in range(0, len(line), 16):
                f.write("  " + "".join(f"0x{b:02X}," for b in line[i : i + 16]) + "\n")
        f.write("};\n")
    print(f"\nwrote {args.output}: {args.size * args.size * 2} bytes "
          f"({args.name}_W x {args.name}_H)", file=sys.stderr)


if __name__ == "__main__":
    main()
